export const CURRENCY_CONFIG: Record<
  CurrencyCode,
  { symbol: string; rateFromInr: number; label: string; locale: string }
> = {
  INR: { symbol: '₹', rateFromInr: 1, label: 'India (INR ₹)', locale: 'en-IN' },
  USD: { symbol: '$', rateFromInr: 0.0119, label: 'Global (USD $)', locale: 'en-US' },
  SGD: { symbol: 'S$', rateFromInr: 0.0159, label: 'SEA (SGD S$)', locale: 'en-SG' },
};

export function formatCurrencyFromInr(amountInr: number, currency: CurrencyCode): string {
  const cfg = CURRENCY_CONFIG[currency];
  const converted = amountInr * cfg.rateFromInr;
  if (currency === 'INR') {
    return `${cfg.symbol}${Math.round(converted).toLocaleString('en-IN')}`;
  }
  return `${cfg.symbol}${converted.toFixed(2)}`;
}

